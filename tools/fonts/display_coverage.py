"""Writes src/ui/display-coverage.ts: the code points every shipped Bricolage
Grotesque weight (500, 700, 800) can draw.

Per `@font-face` rule of src/styles/fonts.css: the WOFF2 cmap intersected with
the rule's unicode-range. Rules of one weight are unioned (latin + latin-ext),
the weights are intersected, and the result is merged into sorted inclusive
ranges. `reading-font.ts` uses it to pick one font for a whole reading.

Usage: display_coverage.py <fonts.css> <public-dir> <out.ts>
"""

import re
import sys
from pathlib import Path

from fontTools.ttLib import TTFont

FAMILY = "Bricolage Grotesque"
WEIGHTS = (500, 700, 800)
HEADER = "// generated by tools/fonts/display_coverage.py — do not edit\n"


def parse_ranges(value):
    ranges = []
    for token in value.split(","):
        token = token.strip()
        m = re.fullmatch(r"U\+([0-9A-Fa-f]+)(?:-([0-9A-Fa-f]+))?", token)
        if m is None:
            sys.exit(f"unparseable unicode-range token: {token!r}")
        low = int(m.group(1), 16)
        ranges.append((low, int(m.group(2), 16) if m.group(2) else low))
    return ranges


def rules(css):
    for block in re.findall(r"@font-face\s*\{([^}]*)\}", css):
        family = re.search(r"font-family:\s*\"([^\"]+)\"", block)
        if family is None or family.group(1) != FAMILY:
            continue
        weight = re.search(r"font-weight:\s*(\d+)", block)
        src = re.search(r"src:\s*url\(\"([^\"]+)\"\)", block)
        urange = re.search(r"unicode-range:\s*([^;]+);", block)
        if weight is None or src is None or urange is None:
            sys.exit(f"incomplete {FAMILY} @font-face rule: {block.strip()!r}")
        yield int(weight.group(1)), src.group(1), parse_ranges(urange.group(1))


def merge(points):
    merged = []
    for cp in sorted(points):
        if merged and cp == merged[-1][1] + 1:
            merged[-1][1] = cp
        else:
            merged.append([cp, cp])
    return merged


def main():
    css_path, public_dir, out_path = sys.argv[1:4]
    by_weight = {}
    for weight, url, ranges in rules(Path(css_path).read_text(encoding="utf-8")):
        path = Path(public_dir) / url.lstrip("/")
        if not path.is_file():
            sys.exit(f"missing font file {path}")
        cmap = set(TTFont(path).getBestCmap())
        allowed = {cp for low, high in ranges for cp in range(low, high + 1)}
        by_weight.setdefault(weight, set()).update(cmap & allowed)
    if not by_weight:
        sys.exit(f"no {FAMILY} @font-face rule in {css_path}")
    missing = [w for w in WEIGHTS if w not in by_weight]
    if missing:
        sys.exit(f"{FAMILY} weights missing from {css_path}: {missing}")
    covered = set.intersection(*(by_weight[w] for w in WEIGHTS))
    lines = [f"  [0x{low:04x}, 0x{high:04x}]," for low, high in merge(covered)]
    out = (
        HEADER
        + "export const displayCoverage: readonly (readonly [number, number])[] = [\n"
        + "\n".join(lines)
        + "\n];\n"
    )
    Path(out_path).write_text(out, encoding="utf-8")
    print(f"display coverage: {len(covered)} code points in {len(lines)} ranges")


main()
