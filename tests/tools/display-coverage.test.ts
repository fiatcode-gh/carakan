import { readFileSync } from "node:fs";
import { describe, expect, test } from "vitest";
import { displayCoverage } from "../../src/ui/display-coverage.ts";

/** Union of the unicode-range of every Bricolage `@font-face` rule. */
function bricolageRanges(): [number, number][] {
  const css = readFileSync("src/styles/fonts.css", "utf8");
  const ranges: [number, number][] = [];
  for (const block of css.matchAll(/@font-face\s*\{([^}]*)\}/g)) {
    const body = block[1] ?? "";
    if (!body.includes('"Bricolage Grotesque"')) continue;
    const list = /unicode-range:\s*([^;]+);/.exec(body)?.[1] ?? "";
    for (const token of list.split(",")) {
      const m = /U\+([0-9A-F]+)(?:-([0-9A-F]+))?/i.exec(token);
      if (m === null) continue;
      const low = parseInt(m[1]!, 16);
      ranges.push([low, m[2] ? parseInt(m[2], 16) : low]);
    }
  }
  return ranges;
}

const covers = (cp: number) =>
  displayCoverage.some(([low, high]) => cp >= low && cp <= high);

describe("generated display coverage", () => {
  test("starts with the generated header", () => {
    const source = readFileSync("src/ui/display-coverage.ts", "utf8");
    expect(
      source.startsWith(
        "// generated by tools/fonts/display_coverage.py — do not edit\n",
      ),
    ).toBe(true);
  });

  test("ranges are sorted, inclusive and non-overlapping", () => {
    expect(displayCoverage.length).toBeGreaterThan(0);
    let previousHigh = -1;
    for (const [low, high] of displayCoverage) {
      expect(low).toBeLessThanOrEqual(high);
      expect(low).toBeGreaterThan(previousHigh + 1);
      previousHigh = high;
    }
  });

  test("ranges lie inside the Bricolage unicode-range declarations", () => {
    const declared = bricolageRanges();
    expect(declared.length).toBeGreaterThan(0);
    for (const [low, high] of displayCoverage) {
      for (const cp of [low, high]) {
        expect(
          declared.some(([l, h]) => cp >= l && cp <= h),
          `U+${cp.toString(16)}`,
        ).toBe(true);
      }
    }
  });

  test("covers a to z and excludes the JGST dotted forms", () => {
    for (let cp = 0x61; cp <= 0x7a; cp++) expect(covers(cp)).toBe(true);
    for (const cp of [0x1e0d, 0x1e33, 0x1e5b, 0x1e6d]) {
      expect(covers(cp), `U+${cp.toString(16)}`).toBe(false);
    }
  });
});
